#!/usr/bin/env python3
"""Following another site: one box shares its inverters' data, another shows them as if they were its own.

A WiFi dongle copes badly with several programs polling it, so a second box must not connect to the same dongles.
Instead the box at the site (the source) keeps polling them and publishes every reply as it came (the bridge's
publish_raw_frames, to lxp/<datalog>/raw/...). The following box runs the bridge's mirror: it subscribes to those
messages and answers its own bridge like the dongle would, so everything downstream (Home Assistant, the
dashboards, the advice) works unchanged. A mirror only reads; it can never change the inverter.

The source ("Share this site" module):
  * Mosquitto gets a second listener, on the network, port 8883, TLS with a certificate made on the box
    (mosquitto/conf.d/share.conf, share.crt, share.key), and an access list (conf.d/acl) in which the account
    `share` may only read lxp/+/raw/#. Mosquitto's first listener stays on localhost.
  * the bridge publishes the raw frames;
  * a share code holds what a follower needs: the addresses, the account's password, the certificate and the
    dongles' ids. "New code" changes the password, which cuts off every box using the old one.

The follower ("Follow a site" module):
  * the pasted code becomes one mirror per dongle (compose services mirror1..mirror4, config in mirror/), which
    check the source's certificate against the one in the code;
  * the dongles go into state/inverters.json marked "remote", with the mirror as their address, so the box's own
    bridge reads them there, and the hourly scan leaves them alone (also when it can see the real dongle on the
    same network: it must not connect to it).

Both boxes have to reach each other's network: the same LAN, or a VPN between the sites.
"""
import base64
import json
import os
import re
import secrets
import socket
import subprocess
import urllib.error
import urllib.request

import solar_setup as ss

PORT = 8883
SERVER_NAME = "solar-share"         # the name in the certificate; the follower checks it whatever address it uses
USER = "share"
NAMESPACE = "lxp"
PREFIX = "SOLARSHARE1-"
MAX_DONGLES = 4                     # mirror1..mirror4 in compose.yaml
HEALTH_PORT = 18080                 # mirrorN's health page on localhost: 18081..18084
DATALOG_RE = re.compile(r"^[A-Za-z0-9]{6,16}$")
HOST_RE = re.compile(r"^[A-Za-z0-9]([A-Za-z0-9.:-]{0,251}[A-Za-z0-9])?$")


class ShareError(Exception):
    pass


# --------------------------------------------------------------------------
# The source: Mosquitto's network listener, the account, the code
# --------------------------------------------------------------------------
def conf_dir(stack):
    return os.path.join(stack, "mosquitto", "conf.d")


def is_sharing(stack):
    import modules
    try:
        return bool(modules.load(stack, "share")["enabled"])
    except Exception:  # noqa: BLE001 - unreadable settings: not sharing
        return False


def _own(path, mode):
    os.chmod(path, mode)
    if os.geteuid() == 0:
        os.chown(path, 1883, 1883)          # Mosquitto's user in its image


def ensure_cert(stack, run=None):
    """The listener's certificate and key, made once (10 years, for SERVER_NAME). Returns the certificate (PEM)."""
    d = conf_dir(stack)
    os.makedirs(d, exist_ok=True)
    crt, key = os.path.join(d, "share.crt"), os.path.join(d, "share.key")
    if not (os.path.exists(crt) and os.path.exists(key)):
        run = run or (lambda cmd: subprocess.run(cmd, capture_output=True, text=True, timeout=60))
        r = run(["openssl", "req", "-x509", "-newkey", "ec", "-pkeyopt", "ec_paramgen_curve:prime256v1", "-nodes",
                 "-days", "3650", "-subj", f"/CN={SERVER_NAME}", "-addext", f"subjectAltName=DNS:{SERVER_NAME}",
                 "-keyout", key, "-out", crt])
        if r.returncode != 0 or not os.path.exists(crt):
            raise ShareError(f"the certificate couldn't be made: {(r.stderr or '').strip()[-200:]}")
        _own(key, 0o600)
        _own(crt, 0o644)
    with open(crt) as f:
        return f.read()


ACL = """# Generated by the "Share this site" module. The box's own accounts keep full access; a following box may only
# read the inverters' raw frames.
user bridge
topic readwrite #

user homeassistant
topic readwrite #

user {user}
topic read {ns}/+/raw/#
"""
LISTENER = """# Generated by the "Share this site" module; removed when it is turned off.
# A second listener, reachable from the network, TLS only. Accounts and the access list apply to both listeners.
acl_file /mosquitto/config/conf.d/acl
listener {port}
certfile /mosquitto/config/conf.d/share.crt
keyfile /mosquitto/config/conf.d/share.key
"""


def write_source(stack, on, run=None):
    """Write (or remove) the listener's files. True if Mosquitto's config changed."""
    d = conf_dir(stack)
    conf = os.path.join(d, "share.conf")
    if not on:
        gone = False
        for f in ("share.conf", "acl"):
            if os.path.exists(os.path.join(d, f)):
                os.remove(os.path.join(d, f))
                gone = True
        return gone
    ensure_cert(stack, run)
    changed = ss.write_if_changed(os.path.join(d, "acl"), ACL.format(user=USER, ns=NAMESPACE), 0o644)
    if os.geteuid() == 0:
        _own(os.path.join(d, "acl"), 0o600)      # Mosquitto wants to own it, unreadable to others (it warns otherwise)
    changed |= ss.write_if_changed(conf, LISTENER.format(port=PORT), 0o644)
    return changed


def password(stack, new=False):
    """The share account's password (state/secrets.json), made on first use; new=True replaces it."""
    path = os.path.join(stack, "state", "secrets.json")
    s = ss.load_json(path, {})
    if new or not s.get("mqtt_share"):
        s["mqtt_share"] = secrets.token_urlsafe(24)
        ss.write_if_changed(path, json.dumps(s, indent=2) + "\n", 0o600)
    return s["mqtt_share"]


def addresses():
    """Where a follower on the same network finds this box: its address, then its name."""
    out = [ss.lan_ip()]
    name = socket.gethostname().split(".")[0]
    if name:
        out.append(f"{name}.local")
    return [a for a in out if a and a != "127.0.0.1"]


def local_dongles(stack):
    inv = ss.load_json(os.path.join(stack, "state", "inverters.json"), {})
    return [{"datalog": dl, "serial": i.get("serial") or ""} for dl, i in sorted(inv.items()) if not i.get("remote")]


def make_code(stack, name="", hosts=None):
    """The share code for this box as it is now."""
    with open(os.path.join(conf_dir(stack), "share.crt")) as f:
        cert = f.read()
    doc = {"v": 1, "name": name[:40], "hosts": hosts if hosts is not None else addresses(), "port": PORT, "user": USER,
           "pass": password(stack), "ns": NAMESPACE, "cert": cert, "dongles": local_dongles(stack)[:MAX_DONGLES]}
    return PREFIX + base64.urlsafe_b64encode(json.dumps(doc, separators=(",", ":")).encode()).decode().rstrip("=")


def read_code(code):
    """A pasted share code as settings for the follower; raises ShareError with what is wrong."""
    code = "".join((code or "").split())
    if not code.startswith(PREFIX):
        raise ShareError("that isn't a share code (it starts with SOLARSHARE1-)")
    raw = code[len(PREFIX):]
    try:
        doc = json.loads(base64.urlsafe_b64decode(raw + "=" * (-len(raw) % 4)))
    except (ValueError, TypeError):
        raise ShareError("the share code is damaged: copy all of it again") from None
    if not isinstance(doc, dict) or doc.get("v") != 1:
        raise ShareError("the share code is from a newer version: update this box first")
    hosts = [h for h in doc.get("hosts") or [] if isinstance(h, str) and HOST_RE.match(h)]
    dongles = [{"datalog": d["datalog"], "serial": str(d.get("serial") or "")[:16]} for d in doc.get("dongles") or []
               if isinstance(d, dict) and DATALOG_RE.match(str(d.get("datalog") or ""))]
    cert = str(doc.get("cert") or "")
    if not dongles:
        raise ShareError("the share code has no inverter dongles: the source box hasn't found its dongles yet")
    if "BEGIN CERTIFICATE" not in cert or not doc.get("pass") or not isinstance(doc.get("port"), int):
        raise ShareError("the share code is incomplete: make a new one on the source box")
    return {"name": str(doc.get("name") or "")[:40], "hosts": hosts, "host": hosts[0] if hosts else "", "port": doc["port"],
            "user": str(doc.get("user") or USER), "password": str(doc["pass"]),
            "ns": str(doc.get("ns") or NAMESPACE) if re.match(r"^[A-Za-z0-9_-]{1,32}$", str(doc.get("ns") or NAMESPACE)) else NAMESPACE,
            "cert": cert, "dongles": dongles[:MAX_DONGLES]}


# --------------------------------------------------------------------------
# The follower: mirrors and the dongles' entries
# --------------------------------------------------------------------------
def mirror_dir(stack):
    return os.path.join(stack, "mirror")


def mirror_config(s, n, dongle):
    return {"mirror": {"enabled": True, "datalog": dongle["datalog"], "listen": f"0.0.0.0:{ss.PORT}",
                       "mqtt": {"host": s["host"], "port": s["port"], "username": s["user"], "password": s["password"],
                                "namespace": s["ns"], "clientName": f"solar-follow-{s['client']}-{n}",
                                "tls": {"enabled": True, "ca_file": "/config/ca.crt", "server_name": SERVER_NAME}}},
            "prometheus": {"enabled": True}}


def write_follow(stack, s):
    """The mirrors' files and the dongles' entries for the follow settings (s["dongles"] empty: none). Returns
    (mirror files changed, inverters changed)."""
    d = mirror_dir(stack)
    os.makedirs(d, exist_ok=True)
    dongles = (s.get("dongles") or [])[:MAX_DONGLES] if s.get("host") else []
    changed = False
    if dongles:
        changed |= ss.write_if_changed(os.path.join(d, "ca.crt"), s["cert"], 0o644)
    for n in range(1, MAX_DONGLES + 1):
        p = os.path.join(d, f"mirror{n}.yml")
        if n <= len(dongles):
            body = "# Generated by the \"Follow a site\" module; edits are overwritten.\n" + json.dumps(mirror_config(s, n, dongles[n - 1]), indent=2) + "\n"
            changed |= ss.write_if_changed(p, body, 0o644)
        elif os.path.exists(p):
            os.remove(p)
            changed = True
    path = os.path.join(stack, "state", "inverters.json")
    inv = ss.load_json(path, {})
    new = {dl: i for dl, i in inv.items() if not i.get("remote")}
    for n, dg in enumerate(dongles, 1):
        new[dg["datalog"]] = {"host": f"mirror{n}", "serial": dg["serial"] or (inv.get(dg["datalog"]) or {}).get("serial", ""),
                              "present": True, "remote": True, "site": s.get("name") or "",
                              "last_seen": (inv.get(dg["datalog"]) or {}).get("last_seen", "")}
    inv_changed = new != inv
    if inv_changed:
        ss.write_if_changed(path, json.dumps(new, indent=2) + "\n", 0o644)
    return changed, inv_changed


def profiles(s):
    """The compose profiles for the mirrors in use."""
    n = len((s.get("dongles") or [])[:MAX_DONGLES]) if s.get("host") else 0
    return [f"follow{i}" for i in range(1, n + 1)]


def mirror_health(n, fetch=None):
    """(ok, text) from mirror n's health page: fresh data from the source, or why not."""
    try:
        if fetch:
            code, body = fetch(n)
        else:
            try:
                with urllib.request.urlopen(f"http://127.0.0.1:{HEALTH_PORT + n}/health", timeout=4) as r:
                    code, body = r.status, ""
            except urllib.error.HTTPError as e:
                code, body = e.code, e.read().decode(errors="replace").strip()
    except OSError as e:
        return False, f"its mirror isn't running ({getattr(e, 'reason', e)})"
    if code in (200, 204):
        return True, "getting data from the source"
    return False, body[:160] or f"its mirror answered {code}"
